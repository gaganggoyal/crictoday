function offer(input: StoredOffer): StoredOffer {
  return input;
}

function at(local: string, timeZone: string) {
  return zonedTimeToUtc(local, timeZone);
}

const demoOffer = (
  id: string,
  seller: string,
  host: string,
  path: string,
  kind: StoredOffer["kind"],
  status: StoredOffer["status"],
  price?: { currency: string; priceFrom: number },
): StoredOffer =>
  offer({
    id,
    sellerName: seller,
    sellerDomain: host,
    url: `https://${host}${path}`,
    kind,
    currency: price?.currency ?? null,
    priceFrom: price?.priceFrom ?? null,
    status,
    lastCheckedAt: status === "pending" ? null : VERIFIED,
    approved: status === "active" || status === "sold_out",
  });

